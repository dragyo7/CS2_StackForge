@dataclass(frozen=True)
class CanonicalMetricDefinition:
    canonical_name: str
    label: str
    unit: str
    value_type: str  # int | float
    valid_min: float
    valid_max: float
    sources: tuple[str, ...]
    provider_field_map: dict[str, str]
    scope: str  # current_rating | rating | performance | recent_or_lifetime
    preference_order: tuple[str, ...]  # recent | lifetime
    used_in_matchmaking: bool
    displayed_in_ui: bool
    notes: str

    def to_dict(self) -> dict:
        return asdict(self)


