CANONICAL_METRICS_BY_NAME: dict[str, CanonicalMetricDefinition] = {m.canonical_name: m for m in CANONICAL_METRICS}


def get_canonical_metric_registry() -> list[dict]:
    return [m.to_dict() for m in CANONICAL_METRICS]


def validate_metric_value(name: str, value: float | int | None) -> float | int | None:
    if value is None:
        return None
    defn = CANONICAL_METRICS_BY_NAME.get(name)
    if not defn:
        return value
    num = float(value)
    if num < defn.valid_min or num > defn.valid_max:
        return None
    return int(round(num)) if defn.value_type == "int" else num
